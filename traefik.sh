#!/bin/sh
set -eu
umask 077
ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
cd "$ROOT"
. "$ROOT/lib/common.sh"
action=${1:-up}
case "$action" in generate|validate|up|down|status|logs) ;; --help|-h)
    printf 'Usage: sh traefik.sh [generate|validate|up|down|status|logs]\n'; exit 0 ;;
    *) die "Unknown command: $action" ;;
esac
[ "$#" -le 1 ] || die 'Expected a single command'
ENV_FILE=${ENV_FILE:-$ROOT/.env}
load_env
defaults

case "$PROJECT_NAME" in ''|[!a-z0-9]*|*[!a-z0-9_-]*) die 'Invalid PROJECT_NAME' ;; esac
case "$PROXY_NETWORK" in ''|[!a-zA-Z0-9]*|*[!a-zA-Z0-9_.-]*) die 'Invalid PROXY_NETWORK' ;; esac
case "$DATA_DIR" in *'$'*|*'`'*|*'"'*|*"'"*|*\\*) die 'DATA_DIR contains unsupported characters' ;; esac
case "$CERTS_EXPORT" in true|false) ;; *) die 'CERTS_EXPORT must be true or false' ;; esac
case "$LOG_LEVEL" in TRACE|DEBUG|INFO|WARN|ERROR|FATAL|PANIC) ;; *) die 'Invalid LOG_LEVEL' ;; esac
printf '%s\n' "$BIND_ADDRESS" | awk -F. 'NF != 4 {exit 1} {for (i=1;i<=4;i++) if ($i !~ /^[0-9]+$/ || $i > 255) exit 1}' || die 'BIND_ADDRESS must be an IPv4 address'
valid_port HTTP_PORT "$HTTP_PORT"
valid_port HTTPS_PORT "$HTTPS_PORT"
[ "$HTTP_PORT" != "$HTTPS_PORT" ] || die 'HTTP_PORT and HTTPS_PORT must differ'
positive_integer LOG_ROTATE_MAX_BACKUPS "$LOG_ROTATE_MAX_BACKUPS"
printf '%s\n' "$LOG_ROTATE_TRIGGER_SIZE" | grep -Eq '^[1-9][0-9]*[kKmMgG]$' || die 'Log size must look like 10m'
case "$LETSENCRYPT_EMAIL" in *@*.*) ;; *) die 'Set a valid LETSENCRYPT_EMAIL' ;; esac
case "$ACME_CA_SERVER" in https://*) ;; *) die 'ACME_CA_SERVER must use HTTPS' ;; esac
if [ -n "$DASHBOARD_HOSTNAME" ]; then
    printf '%s\n' "$DASHBOARD_HOSTNAME" | grep -Eq '^([a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?\.)+[a-zA-Z]{2,63}$' || die 'Invalid DASHBOARD_HOSTNAME'
    DASHBOARD_ENABLED=true
else
    DASHBOARD_ENABLED=false
fi
export DASHBOARD_ENABLED

ports=$(printf '%s' "$CUSTOM_PORTS" | tr ',' ' ' | awk '{$1=$1;print}')
seen=' '
for port in $ports; do
    valid_port CUSTOM_PORTS "$port"
    case "$seen" in *" $port "*) die "Duplicate custom port: $port" ;; esac
    case "$port" in 80|443|8080) die "Custom port $port conflicts with a built-in entrypoint" ;; esac
    if [ "$port" = "$HTTP_PORT" ] || [ "$port" = "$HTTPS_PORT" ]; then
        die "Custom port $port conflicts with HTTP(S)"
    fi
    seen="$seen$port "
done

if [ "$action" = generate ] || [ "$action" = validate ] || [ "$action" = up ]; then
    generated=$(mktemp "$ROOT/.compose.generated.XXXXXX")
    trap 'rm -f "$generated"' EXIT
    {
        printf '# Generated by traefik.sh; edit .env instead.\nservices:\n  traefik:\n    environment:\n      TRAEFIK_API: "%s"\n' "$DASHBOARD_ENABLED"
        for port in $ports; do
            printf '      "TRAEFIK_ENTRYPOINTS_TCP-%s_ADDRESS": ":%s"\n' "$port" "$port"
            printf '      "TRAEFIK_ENTRYPOINTS_UDP-%s_ADDRESS": ":%s/udp"\n' "$port" "$port"
        done
        if [ -n "$ports" ]; then
            printf '    ports:\n'
            for port in $ports; do
                printf '      - "%s:%s:%s/tcp"\n      - "%s:%s:%s/udp"\n' "$BIND_ADDRESS" "$port" "$port" "$BIND_ADDRESS" "$port" "$port"
            done
        fi
        if [ "$DASHBOARD_ENABLED" = true ]; then
            cat <<'YAML'
    labels:
      traefik.enable: "true"
      traefik.http.routers.traefik-dashboard-http.entrypoints: http
      traefik.http.routers.traefik-dashboard-http.rule: Host(`${DASHBOARD_HOSTNAME}`)
      traefik.http.routers.traefik-dashboard-http.service: api@internal
      traefik.http.routers.traefik-dashboard-http.middlewares: traefik-dashboard-redirect
      traefik.http.middlewares.traefik-dashboard-redirect.redirectscheme.scheme: https
      traefik.http.middlewares.traefik-dashboard-redirect.redirectscheme.port: "${HTTPS_PORT}"
      traefik.http.routers.traefik-dashboard-https.entrypoints: https
      traefik.http.routers.traefik-dashboard-https.rule: Host(`${DASHBOARD_HOSTNAME}`)
      traefik.http.routers.traefik-dashboard-https.service: api@internal
      traefik.http.routers.traefik-dashboard-https.tls: "true"
      traefik.http.routers.traefik-dashboard-https.tls.certresolver: letsencrypt
      traefik.http.routers.traefik-dashboard-https.middlewares: traefik-dashboard-auth
      traefik.http.middlewares.traefik-dashboard-auth.basicauth.usersfile: /auth/dashboard.htpasswd
      traefik.http.middlewares.traefik-dashboard-auth.basicauth.removeheader: "true"
YAML
        fi
    } > "$generated"
    mv "$generated" "$ROOT/compose.generated.yaml"
    trap - EXIT
    printf 'Generated compose.generated.yaml\n'
fi
[ "$action" != generate ] || exit 0
command -v docker >/dev/null 2>&1 || die 'Docker is required for this command'
docker compose version >/dev/null 2>&1 || die 'Docker Compose v2 is required'
[ -f "$ROOT/compose.generated.yaml" ] || die 'Run generate first'
compose config --quiet
[ "$action" != validate ] || exit 0

case "$action" in
    up)
        mkdir -p "$DATA_DIR/acme" "$DATA_DIR/auth" "$DATA_DIR/certs"
        touch "$DATA_DIR/acme/acme.json"
        chmod 700 "$DATA_DIR/acme" "$DATA_DIR/auth" "$DATA_DIR/certs"
        chmod 600 "$DATA_DIR/acme/acme.json"
        if [ "$DASHBOARD_ENABLED" = true ] && [ ! -s "$DATA_DIR/auth/dashboard.htpasswd" ]; then
            die 'Dashboard credentials missing; run sh traefik-basic-auth.sh first'
        fi
        if ! docker network inspect "$PROXY_NETWORK" >/dev/null 2>&1; then
            docker network create "$PROXY_NETWORK" >/dev/null
        fi
        if [ "$CERTS_EXPORT" = true ]; then compose build certs-exporter; fi
        compose up -d --wait --wait-timeout 120 --remove-orphans
        # Compose keeps stopped-profile services in its model; --remove-orphans alone
        # does not remove an exporter that was enabled by an earlier deployment.
        if [ "$CERTS_EXPORT" = false ]; then
            compose --profile certs rm --stop --force certs-exporter
        fi
        printf 'Traefik deployment is healthy.\n'
        ;;
    down) compose down ;;
    status) compose ps ;;
    logs) compose logs --tail 100 ;;
esac
